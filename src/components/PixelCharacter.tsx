export function PixelCharacter({ className, size = 192 }: PixelCharacterProps) {
  const rows = PIXELS.length;
  const cols = PIXELS[0].length;
  const cell = 1;
  return (
    <svg
      width={size}
      height={(size * rows) / cols}
      viewBox={`0 0 ${cols * cell} ${rows * cell}`}
      className={className}
      shapeRendering="crispEdges"
      xmlns="http://www.w3.org/2000/svg"
    >
      {PIXELS.map((row, y) =>
        row.map((v, x) =>
          v === 0 ? null : (
            <rect
              key={`${x}-${y}`}
              x={x * cell}
              y={y * cell}
              width={cell}
              height={cell}
              fill={PALETTE[v]}
            />
          ),
        ),
      )}
    </svg>
  );
}
